"""Write the results report (Markdown) from a ``python -m pollbench run`` JSON.

    python -m pollbench.report results/epoch-2026-10-10.json --out docs/results-epoch-2026-10-10.md

Every number in the report is read from the JSON, so the report cannot drift
from the run. Prose that depends on a result is chosen from the result.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

from .ratings import GRADE_BANDS, GRADE_PROB, MAX_RHAT, MIN_MODELS_FOR_GRADE

METHOD_LABEL = {"benchmark_mean": "`benchmark_mean`", "mean_rank": "`mean_rank`", "low_rank_1": "`low_rank_1`",
                "eci_ls": "`eci_ls` (Epoch's index form)", "hier_beta": "`hier_beta`"}


def _iv(lo: float, hi: float, d: int = 3) -> str:
    return f"{lo:.{d}f} to {hi:.{d}f}"


def _names(xs: list[str]) -> str:
    return ", ".join(xs) if xs else "none"


def _letters_line(label: str, block: dict) -> str:
    ch = block["letters_changed"]
    out = f"- {label}: {len(ch)} of {block['n_comparable']} benchmarks graded in both fits change letter ({_names(ch)})"
    if block.get("n_not_assessable"):
        out += f"; {block['n_not_assessable']} graded in the main fit could not be compared (ungraded in this one)"
    return out + "."


def render(d: dict) -> str:
    rows = d["benchmarks"]
    graded = [r for r in rows if r["grade"] != "ungraded"]
    counts = {g: sum(r["grade"] == g for r in rows) for g in ["A", "B", "C", "D", "ungraded"]}
    cond = d["conditions"]
    c1, c1b = cond["1_beats_mean_rank_split_A"], d["condition_1b_vs_eci_ls"]
    c2 = cond["2_coverage90_in_0.80_0.95"]
    c3, c4 = cond["3_temporal_stability_spearman_ge_0.70"], cond["4_reliability_vs_skill_spearman_ge_0.50"]
    held = d["heldout"]
    diag = d["diagnostics"]
    bench_rhat = max((r["rhat"] for r in rows if r["rhat"] is not None), default=float("nan"))
    sf, fl = d["second_factor_check"], d.get("floor_model_check")
    rob = d["robustness"]
    L = []
    L.append("# Results on the Epoch table, 2026-10-10")
    L.append("")
    L.append(f"Protocol: {d['protocol']} (`docs/protocol.md`).")
    L.append(f"Data: Epoch AI `processed_data_for_eci.csv` (file SHA-256 `{d.get('file_sha256', '')[:16]}…`), CC BY 4.0, attributed to Epoch AI.")
    L.append(f"{d['n_models']} models, {d['n_benchmarks']} benchmarks, {d['n_cells']:,} scores; data digest `{d['data_digest'][:16]}`.")
    L.append("This file is generated by `python -m pollbench.report` from `results/epoch-2026-10-10.json`; edit the generator, not this file.")
    L.append("")
    L.append("## Headline")
    L.append("")
    L.append(f"On scores it never saw (Split A), the model's mean CRPS is {abs(c1b['mean_diff']):.4f} lower than the form Epoch uses for its Capabilities Index (`eci_ls`): 95% interval {_iv(abs(c1b['hi']), abs(c1b['lo']), 4)} resampling models, {_iv(abs(c1b['crossed_hi']), abs(c1b['crossed_lo']), 4)} resampling models and benchmarks together.")
    L.append("That gain is small. What the model adds over Epoch's form is calibrated uncertainty and a per-benchmark noise estimate, not a better index.")
    L.append(f"Against averaging each model's ranks (`mean_rank`) the gain is {abs(c1['mean_diff']):.3f} ({_iv(abs(c1['hi']), abs(c1['lo']))}; crossed {_iv(abs(c1['crossed_hi']), abs(c1['crossed_lo']))}).")
    L.append("")
    L.append("## Reporting conditions")
    L.append("")
    n_hold = sum(v["holds"] for v in cond.values())
    L.append(f"{n_hold} of 4 pre-registered conditions hold. Conditions 3 and 4 are consistency checks, not tests of validity: 3 compares the full fit with a fit on a subset of the same data, and 4 compares two variance-explained quantities from the same fit, which agree whenever the fit is internally consistent (in the simulation study 4 passes under a strong second factor that biases reliability).")
    L.append("")
    L.append("| condition | holds | value |")
    L.append("| --- | --- | --- |")
    L.append(f"| 1. `hier_beta` beats `mean_rank` on Split A | {'yes' if c1['holds'] else 'no'} | CRPS difference {c1['mean_diff']:+.3f} ({_iv(c1['lo'], c1['hi'])}) |")
    L.append(f"| 2. held-out 90% coverage in [0.80, 0.95] | {'yes' if c2['holds'] else 'no'} | {c2['coverage90']:.3f} |")
    L.append(f"| 3. reliability from models up to {c3['cutoff_date']} vs full fit, Spearman ≥ 0.70 (consistency) | {'yes' if c3['holds'] else 'no'} | {c3['rho']:.2f} over {c3['n_benchmarks']} benchmarks |")
    L.append(f"| 4. reliability vs held-out skill, Spearman ≥ 0.50 (consistency) | {'yes' if c4['holds'] else 'no'} | {c4['rho']:.2f} over {c4['n_benchmarks']} benchmarks |")
    L.append("")
    L.append("## Convergence")
    L.append("")
    L.append(f"NUTS, 4 chains started from dispersed points, 500 warmup and 1,000 kept draws each. Rank-normalised split R-hat (bulk and folded): worst over every benchmark's parameters {bench_rhat:.3f}, worst over all parameters {diag['rhat_max']:.3f}; minimum bulk ESS {diag['ess_min']:.0f}; {diag.get('divergences', 0)} divergent transitions.")
    L.append(f"A benchmark is graded only if its parameters have R-hat ≤ {MAX_RHAT} and it has at least {MIN_MODELS_FOR_GRADE} models.")
    bad = {k: v for k, v in d["robustness_fit_diagnostics"].items() if v.get("rhat_max", 0) > 1.05}
    if bad:
        L.append("Robustness refits whose worst R-hat exceeds 1.05 (benchmarks above the gate are ungraded in those fits and drop out of the comparisons below): " + ", ".join(f"{k} {v['rhat_max']:.2f}" for k, v in bad.items()) + ".")
    else:
        L.append("Every robustness refit has worst R-hat at or below 1.05.")
    L.append("")
    L.append("## Predictive comparison")
    L.append("")
    L.append(f"Mean held-out CRPS, lower is better. Split A is five-fold over cells ({held['kfold']['n_cells']:,} held out); Split B holds out half the scores of the newest quarter of models ({held['frontier']['n_cells']:,}).")
    L.append("")
    L.append("| method | Split A | Split B | 90% coverage A | 90% coverage B |")
    L.append("| --- | --- | --- | --- | --- |")
    for m in ["benchmark_mean", "mean_rank", "low_rank_1", "eci_ls", "hier_beta"]:
        L.append(f"| {METHOD_LABEL[m]} | {held['kfold']['mean_crps'][m]:.3f} | {held['frontier']['mean_crps'][m]:.3f} | {held['kfold']['coverage90'][m]:.2f} | {held['frontier']['coverage90'][m]:.2f} |")
    fe = next(c for c in held["frontier"]["hier_beta_vs"] if c["b"] == "eci_ls")
    L.append("")
    L.append(f"On Split B `hier_beta` minus `eci_ls` is {fe['mean_diff']:+.4f} ({_iv(fe['lo'], fe['hi'], 4)}; crossed {_iv(fe['crossed_lo'], fe['crossed_hi'], 4)}).")
    L.append("")
    L.append("## Ratings")
    L.append("")
    L.append(f"Read the interval, not the letter. A letter is the highest band whose threshold reliability clears with probability ≥ {GRADE_PROB:.0%} (A ≥ {GRADE_BANDS[0][0]}, B ≥ {GRADE_BANDS[1][0]}, C ≥ {GRADE_BANDS[2][0]}); D means not shown to clear {GRADE_BANDS[2][0]}, not that it fails to.")
    L.append(f"{counts['A']} benchmarks are A, {counts['B']} B, {counts['C']} C, {counts['D']} D, and {counts['ungraded']} are ungraded.")
    widths = [r["reliability_hi"] - r["reliability_lo"] for r in graded]
    L.append(f"The median width of a graded benchmark's 90% interval is {np.median(widths):.2f}.")
    L.append("")
    L.append("### Reliability depends on who was scored")
    L.append("")
    rel = [r["reliability_mean"] for r in graded]
    allm = [r["all_models_reliability_mean"] for r in graded]
    sp = [r["capability_spread"] for r in graded]
    nm = [r["n_models"] for r in graded]
    ssd = [d["score_sd"][r["benchmark"]] for r in graded] if "score_sd" in d else None
    band = lambda x: next((g for (t, g) in GRADE_BANDS if x >= t), "D")
    differ = sum(band(a) != band(b) for a, b in zip(rel, allm))
    L.append("Reliability is a ratio over the models actually scored on the benchmark, so a benchmark run only on a narrow slice of capability reads low however sharp it is.")
    L.append(f"Across the {len(graded)} graded benchmarks, reliability has rank correlation {spearmanr(rel, sp).statistic:.2f} with the capability range scored (as a share of the range over all models)" +
             (f", {spearmanr(rel, ssd).statistic:.2f} with the spread of scores" if ssd else "") + f" and {spearmanr(rel, nm).statistic:.2f} with the number of models.")
    L.append(f"Holding the population fixed (every model in the table), reliability ranks benchmarks with correlation {spearmanr(rel, allm).statistic:.2f} to the scored-models version, and the band of the posterior mean differs for {differ} of {len(graded)}.")
    L.append("Both are reported; the grade uses the scored-models version, as registered.")
    L.append("")
    L.append("## Robustness")
    L.append("")
    dev = rob["drop_developer_reported"]
    L.append(f"- Developer-reported scores: the rule flags {dev['n_flagged']} scores; dropping them and re-applying looser minimums (3 per benchmark and per model) leaves {dev['n_cells']:,} scores and {dev['n_models']} models. {len(dev['letters_changed'])} of {dev['n_comparable']} benchmarks graded in both fits change letter ({_names(dev['letters_changed'])}); {dev['n_not_assessable']} could not be compared.")
    L.append(_letters_line("Repeat fit with another seed", rob["seed_repeat"]))
    L.append(_letters_line("Scores clipped at 0.02 instead of 0.005", rob["clip_0.02"]))
    L.append(_letters_line("Precision-prior scale 0.5", rob["precision_scale_0.5"]))
    L.append(_letters_line("Precision-prior scale 2", rob["precision_scale_2"]))
    sub = rob["subsets_70pct"]["changes_per_benchmark"]
    stable = sum(v["changes"] == 0 for v in sub.values())
    L.append(f"- Five refits on random 70% subsets of models: {stable} of {len(sub)} graded benchmarks keep their letter in every subset where they are graded; the rest change at least once.")
    lomo = rob["leave_one_model_out"]
    for m, v in lomo.items():
        L.append(_letters_line(f"Leaving out {m} (one of the three models with the most scores)", v))
    L.append("")
    L.append("## Is capability one number?")
    L.append("")
    L.append(f"A posterior predictive check compares the mean squared correlation of residuals over {sf['n_pairs']} benchmark pairs (sharing at least 12 models) with the same statistic on tables simulated from the fit: observed {sf['statistic']:.3f}, simulated {sf['reference_mean']:.3f} (95th percentile {sf['reference_p95']:.3f}), p = {sf['p_value']:.3f}.")
    cal = d.get("second_factor_calibration")
    if cal:
        s = cal["summary"]
        L.append(f"On simulated tables the check rejects {s['0.0']['rejections']} of {s['0.0']['reps']} without a second factor, {s['0.3']['rejections']} of {s['0.3']['reps']} with a weak one (loading sd 0.3) and {s['0.8']['rejections']} of {s['0.8']['reps']} with a strong one (0.8), so it is well calibrated but would often miss a weak second factor.")
    if fl:
        f2 = fl["second_factor_check"]
        L.append(f"The audit pointed out that the most correlated residuals sit among older multiple-choice benchmarks with chance floors, which the model does not have. Refitting with a per-benchmark floor gives observed {f2['statistic']:.3f} against simulated {f2['reference_mean']:.3f} (p = {f2['p_value']:.3f}).")
        floors = sorted(((v[0], b) for b, v in fl["floors"].items()), reverse=True)[:6]
        L.append("The largest fitted floors: " + ", ".join(f"{b} {v:.2f}" for v, b in floors) + ".")
        shrink = 1 - (f2["statistic"] - f2["reference_mean"]) / max(sf["statistic"] - sf["reference_mean"], 1e-9)
        L.append(f"The floor removes {shrink:.0%} of the excess residual correlation.")
        if f2["p_value"] < 0.05:
            L.append("Leftover structure remains with floors, so part of it is not link misfit; the ratings are reliability with respect to one general factor.")
        else:
            L.append("With floors the check no longer rejects, so the leftover structure is consistent with link misfit at the floor rather than a second capability.")
        top = fl["residual_pairs"]["most_positive"][:5]
        L.append("Most correlated residual pairs with floors (exploratory): " + "; ".join(f"{q['a']} with {q['b']} ({q['r']:+.2f}, {q['n_models']} models)" for q in top) + ".")
    L.append("")
    L.append("## What these results do not show")
    L.append("")
    L.append("- That a benchmark measures what it says it measures. Reliability is internal consistency with the other benchmarks in the table.")
    L.append("- That the table is representative: it is the set Epoch fits its index on, already filtered to benchmarks that fit that index.")
    L.append("- That the simulation study validates coverage on real data: its generator is the fitted model, so its recovery numbers are a best case.")
    return "\n".join(L) + "\n"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("results")
    ap.add_argument("--calibration", default=None, help="second-factor calibration JSON to quote")
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    d = json.loads(Path(a.results).read_text())
    if a.calibration:
        d["second_factor_calibration"] = json.loads(Path(a.calibration).read_text())
    Path(a.out).write_text(render(d), encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
